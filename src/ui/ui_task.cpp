static IApp* current_app = nullptr;

static void _run_slide_transition(LGFX_Sprite* old_snap, LGFX_Sprite* new_snap) {
    const int SLIDE_FRAMES = 15;
    const int W = tft.width();

    for (int i = 1; i <= SLIDE_FRAMES; i++) {
        float t = (float)i / (float)SLIDE_FRAMES;
        
        // Cubic ease-out: f(t) = 1 - (1-t)^3
        float inv = 1.0f - t;
        float eased = 1.0f - (inv * inv * inv);
        
        int offset = (int)(eased * (float)W);

        // Clear canvas with black first to ensure no ghosting in edges
        canvas.fillSprite(tft.color565(0, 0, 0));

        // Parallax effect: old frame slides out at half speed drawn onto canvas (0-based Y offset)
        int old_x = -(offset / 2);
        old_snap->pushSprite(&canvas, old_x, 0);
        
        // Subtle edge shadow/separator drawn onto canvas
        if (offset < W && W - offset > 0) {
            canvas.drawFastVLine(W - offset - 1, 0, canvas.height(), canvas.color565(30, 30, 30));
            if (W - offset > 1) {
                canvas.drawFastVLine(W - offset - 2, 0, canvas.height(), canvas.color565(15, 15, 15));
            }
        }

        // Draw new frame sliding in over the old one onto canvas (0-based Y offset)
        new_snap->pushSprite(&canvas, W - offset, 0);

        // Push the completely rendered composite canvas frame to physical display at -4 Y offset
        canvas.pushSprite(&tft, 0, -4);

        vTaskDelay(pdMS_TO_TICKS(20)); // ~50fps logic update
    }
}

// ─── App switch with slide + safe dynamic-app deletion ────────────────────
void switch_to_app(IApp* next_app) {
    if (!next_app) return;

    // ── Capture old frame for the slide animation ────────────────────────
    // Allocate snapshot sprites in PSRAM to avoid touching internal SRAM.
    LGFX_Sprite old_snap(&tft);
    LGFX_Sprite new_snap(&tft);
    old_snap.setPsram(true);
    new_snap.setPsram(true);
    old_snap.setColorDepth(16);
    new_snap.setColorDepth(16);
    bool old_snap_ok = old_snap.createSprite(tft.width(), tft.height() + 4);
    bool new_snap_ok = new_snap.createSprite(tft.width(), tft.height() + 4);
    bool transition_ok = old_snap_ok && new_snap_ok;
    if (!transition_ok) {
        if (old_snap_ok) old_snap.deleteSprite();
        if (new_snap_ok) new_snap.deleteSprite();
        ESP_LOGW(TAG, "Skipping app transition animation due to sprite allocation failure");
    }

    // Render current state into old_snap
    if (transition_ok && current_app) {
        current_app->render(&old_snap);
    }

    // ── Exit current app ─────────────────────────────────────────────────
    IApp* old_app = current_app;
    if (old_app) {
        old_app->exit();
    }

    // ── Bring in the new app ─────────────────────────────────────────────
    current_app = next_app;
    current_app->init();

    // ── Render first frame of new app into new_snap ──────────────────────
    if (transition_ok) {
        theme_update();  // Ensure theme interpolation is current
        current_app->render(&new_snap);

        // Play the slide animation
        _run_slide_transition(&old_snap, &new_snap);

        old_snap.deleteSprite();
        new_snap.deleteSprite();
    }

    // ── Delete dynamic (heap-allocated) old app AFTER transition is done ─
    // This is the fix for the App_NES SRAM leak: safe because exit() has
    // already run, the new app is fully initialised, and the transition
    // sprites that referenced old_app's pixels have already been pushed.
    if (old_app && old_app->isDynamic()) {
        ESP_LOGI(TAG, "Deleting dynamic app instance (leak fix)");
        delete old_app;
    }
}

void switch_to_grid() {
    switch_to_app(&app_grid);
}

static void ui_task_runner(void *arg) {
    ESP_LOGI(TAG, "UI Task Started (Event-Driven Architecture)");

    tft.init();
    tft.setRotation(1);

    nvs_handle_t handle;
    if (nvs_open("ui_cfg", NVS_READONLY, &handle) == ESP_OK) {
        nvs_get_u8(handle, "brightness", &current_brightness);
        nvs_close(handle);
    }
    tft.setBrightness(current_brightness);

    canvas.setColorDepth(16);
    canvas.setPsram(true);
    if (!canvas.createSprite(tft.width(), tft.height() + 4)) {
        ESP_LOGE(TAG, "Failed to create main UI canvas");
        vTaskDelete(nullptr);
        return;
    }

    theme_init();

    app_grid.registerApp("OTA System",  icon_ota,       &app_ota);
    app_grid.registerApp("Torch",       icon_torch,     &app_torch);
    app_grid.registerApp("AI Code",     icon_aicode,    &app_aicode);
    app_grid.registerApp("Settings",    icon_settings,  &app_settings);
    app_grid.registerApp("Game Store",  icon_games,     &app_gamestore);
    app_grid.registerApp("Hack Store",  icon_app_store, &app_hackstore);
    app_grid.registerApp("Clock",       icon_weather,   &app_clockweather);
    app_grid.registerApp("Pomodoro",    icon_pomodoro,  &app_pomodoro);

    // Use a direct init for the first launch — no slide needed at boot
    current_app = &app_grid;
    current_app->init();

    const TickType_t xFrameTime = pdMS_TO_TICKS(25); // 40 FPS target
    TickType_t xLastWakeTime = xTaskGetTickCount();

    while (1) {
        // Process input events (non-blocking)
        input_event_t ev = input_mgr_get_event();
        if (ev != BTN_NONE) {
            idle_mgr_feed();
            ESP_LOGD(TAG, "DISPATCH ev=%d to %s", ev,
                current_app ? "app" : "null");
        }
        if (current_app) {
            current_app->handleInput(ev);
        }

        // Update animations
        theme_update();
        if (current_app) {
            current_app->loop();
        }

        // Render
        if (current_app) {
            current_app->render(&canvas);
        }

        // Idle countdown overlay
        if (idle_mgr_get_state() == IDLE_STATE_COUNTDOWN) {
            int rem = idle_mgr_get_countdown_remaining();
            int w = canvas.width();
            int h = canvas.height();

            int bw = 140, bh = 60;
            int bx = (w - bw) / 2, by = (h - bh) / 2;

            canvas.fillRoundRect(bx, by, bw, bh, 8, canvas.color565(5, 5, 15));
            canvas.drawRoundRect(bx, by, bw, bh, 8, theme_get_accent());

            int bar_w = 6, bar_max_h = bh - 20;
            int bar_x = bx + 12, bar_y = by + 10;

            canvas.drawRect(bar_x, bar_y, bar_w, bar_max_h, theme_get_text_dim());

            int fill_h = (int)(bar_max_h * (rem / 10.0f));
            if (fill_h > 0) {
                canvas.fillRect(bar_x + 1, bar_y + (bar_max_h - fill_h), bar_w - 2, fill_h, theme_get_accent());
            }

            canvas.setTextDatum(textdatum_t::middle_left);
            canvas.setTextColor(theme_get_text());
            canvas.setFont(&fonts::Font2);
            char buf[16];
            snprintf(buf, sizeof(buf), "%ds", rem);
            canvas.drawString(buf, bar_x + 15, bar_y + 8);

            canvas.setFont(&fonts::Font0);
            canvas.drawString("SLEEPING SOON", bar_x + 15, bar_y + 22);

            canvas.setTextColor(theme_get_text_dim());
            canvas.drawString("Any key to stay", bar_x + 15, bar_y + 34);
        }

        canvas.pushSprite(0, -4);

        // Precise frame timing
        vTaskDelayUntil(&xLastWakeTime, xFrameTime);
    }
}

extern "C" void ui_task_init(void) {
    xTaskCreatePinnedToCore(
        ui_task_runner,
        "ui_task",
        8192,
        NULL,
        5,
        NULL,
        1
    );
}
